"""Módulo 5. Análisis prescriptivo (predicciones )
Calcula el horario de mañana y lo escribe en el canal `Sueno_Predicciones`, que la ESP32 lee de día.

**hora_dormir_pred:** promedio de hora de acostarse del tipo de día de mañana (fin de semana o entre semana).

**hora_despertar_pred:** se mantiene la hora objetivo del usuario (5:00).

**rampa_min:** amanecer más largo cuando el modelo predice que el usuario tarda más en levantarse (10 a 30 min).
"""

