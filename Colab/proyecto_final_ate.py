"""## Módulo 1. Carga de datos"""

def leer_thingspeak():
    url = f"https://api.thingspeak.com/channels/{CANAL_DATOS}/feeds.csv?results=8000"
    try:
        raw = pd.read_csv(url)
    except:
        return pd.DataFrame()
    raw = raw.rename(columns={'field1': 'dia', 'dia_semana': 'dia', 'field2': 'hora_acostarse',
                              'field3': 'latencia_min', 'field4': 'hora_despertar_pred',
                              'field5': 'hora_levantado', 'field6': 'tiempo_apagar_min',
                              'field7': 'luz_pct', 'field8': 'evento'})
    df = raw[raw['evento'] == 2]
    df = df[['dia', 'hora_acostarse', 'latencia_min', 'hora_despertar_pred',
             'hora_levantado', 'tiempo_apagar_min', 'luz_pct']].dropna().astype(float)
    df = df[df['hora_acostarse'] > 0]
    df['origen'] = 'ThingSpeak'
    return df

def simular_noches(n, semilla=42):
    rng = np.random.default_rng(semilla)
    dia = np.array([(i % 7) + 1 for i in range(n)])
    finde = np.isin(dia, [5, 6]).astype(float)
    acostarse = 22.0 + 1.2 * finde + rng.normal(0, 0.45, n)
    latencia = np.clip(12 + 7 * (acostarse - 22) + rng.normal(0, 4, n), 2, 60)
    luz = np.clip(rng.normal(45, 18, n), 5, 95)
    apagar = np.clip(18 + 25 * (acostarse - 22) + 15 * finde - 0.15 * (luz - 45) + rng.normal(0, 6, n), 0, 120)
    return pd.DataFrame({'dia': dia, 'hora_acostarse': acostarse, 'latencia_min': latencia,
                         'hora_despertar_pred': 5.0, 'hora_levantado': 5.0 + apagar / 60,
                         'tiempo_apagar_min': apagar, 'luz_pct': luz, 'origen': 'Simulado'})

def cargardatos():
    reales = leer_thingspeak()
    faltan = max(0, MIN_NOCHES - len(reales))
    df = pd.concat([reales, simular_noches(faltan)], ignore_index=True).tail(MIN_NOCHES)
    df['hora_acostarse'] = np.where(df['hora_acostarse'] < 12, df['hora_acostarse'] + 24, df['hora_acostarse'])
    return df.reset_index(drop=True)

